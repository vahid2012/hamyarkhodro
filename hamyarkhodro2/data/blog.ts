export const POST_BY_SLUG: Record<string, BlogPost> = Object.fromEntries(
  BLOG_POSTS.map((p) => [p.slug, p]),
);

export function postBySlug(slug: string): BlogPost | undefined {
  return POST_BY_SLUG[slug];
}
